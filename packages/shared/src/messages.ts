const dictionaries: Record<AppLocale, Record<MessageKey, string>> = { fi, sv, en };

export function isMessageKey(value: string): value is MessageKey {
  return value in fi;
}

export function t(locale: AppLocale, key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = dictionaries[locale] ?? fi;
  let text = dict[key] ?? fi[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function translateError(locale: AppLocale, code: string | undefined, fallback: string): string {
  if (!code) {
    return fallback;
  }
  const key = `error.${code}`;
  if (isMessageKey(key)) {
    return t(locale, key);
  }
  return fallback;
}

export function statusMessageKey(status: string): MessageKey | null {
  const key = `status.${status}`;
  return isMessageKey(key) ? key : null;
}

